using System;
class Arithmetic {
    static void Main() {
        int a = 10;
        int b = 3;
        Console.WriteLine("Add:");
        Console.WriteLine(a + b);
        Console.WriteLine("Sub:");
        Console.WriteLine(a - b);
        Console.WriteLine("Mul:");
        Console.WriteLine(a * b);
        Console.WriteLine("Div:");
        Console.WriteLine(a / b);
        Console.WriteLine("Mod:");
        Console.WriteLine(a % b);
    }
}